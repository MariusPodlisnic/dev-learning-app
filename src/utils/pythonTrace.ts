import type { LessonEnrichment } from "../constants/curriculum";
import type { Lesson } from "../types/lesson";

export interface TraceVariableSnapshot {
  value: string;
  type: string;
  changed?: boolean;
}

export interface PythonTraceFrame {
  stepIndex: number;
  line: number;
  codeLine: string;
  event: "call" | "line" | "return" | "exception";
  funcName: string;
  depth: number;
  callStack: string[];
  locals: Record<string, TraceVariableSnapshot>;
  changedVars: string[];
  returnValue: string | null;
  exception: string | null;
  stdout: string;
}

export interface PythonTraceResult {
  ok: boolean;
  frames: PythonTraceFrame[];
  totalSteps: number;
  truncated: boolean;
  driverUsed: string;
  finalStdout: string;
  error?: string;
}

export interface TraceDriverResolution {
  driverCode: string;
  autoGenerated: boolean;
}

function splitTopLevelItems(source: string): string[] {
  const items: string[] = [];
  let depthParen = 0;
  let depthBracket = 0;
  let depthBrace = 0;
  let quote: '"' | "'" | null = null;
  let escaped = false;
  let start = 0;

  for (let i = 0; i < source.length; i++) {
    const ch = source[i];
    if (quote) {
      if (escaped) {
        escaped = false;
      } else if (ch === "\\") {
        escaped = true;
      } else if (ch === quote) {
        quote = null;
      }
      continue;
    }
    if (ch === '"' || ch === "'") {
      quote = ch;
      continue;
    }
    if (ch === "(") depthParen++;
    else if (ch === ")") depthParen = Math.max(0, depthParen - 1);
    else if (ch === "[") depthBracket++;
    else if (ch === "]") depthBracket = Math.max(0, depthBracket - 1);
    else if (ch === "{") depthBrace++;
    else if (ch === "}") depthBrace = Math.max(0, depthBrace - 1);
    else if (
      ch === "," &&
      depthParen === 0 &&
      depthBracket === 0 &&
      depthBrace === 0
    ) {
      items.push(source.slice(start, i).trim());
      start = i + 1;
    }
  }

  const tail = source.slice(start).trim();
  if (tail) items.push(tail);
  return items;
}

function extractBalancedSlice(
  text: string,
  openIndex: number,
  openChar: string,
  closeChar: string,
): string | null {
  let depth = 0;
  let quote: '"' | "'" | null = null;
  let escaped = false;

  for (let i = openIndex; i < text.length; i++) {
    const ch = text[i];
    if (quote) {
      if (escaped) escaped = false;
      else if (ch === "\\") escaped = true;
      else if (ch === quote) quote = null;
      continue;
    }
    if (ch === '"' || ch === "'") {
      quote = ch;
      continue;
    }
    if (ch === openChar) depth++;
    else if (ch === closeChar) {
      depth--;
      if (depth === 0) {
        return text.slice(openIndex + 1, i);
      }
    }
  }
  return null;
}

function countDeclaredParams(paramListRaw: string): number {
  const params = splitTopLevelItems(paramListRaw).filter(
    (p) => p && p !== "self" && p !== "cls",
  );
  return params.length;
}

function updateParenDepth(line: string, startDepth: number): number {
  let depth = startDepth;
  let quote: '"' | "'" | null = null;
  let escaped = false;

  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (quote) {
      if (escaped) escaped = false;
      else if (ch === "\\") escaped = true;
      else if (ch === quote) quote = null;
      continue;
    }
    if (ch === '"' || ch === "'") {
      quote = ch;
      continue;
    }
    if (ch === "#") break;
    if (ch === "(" || ch === "[" || ch === "{") depth++;
    else if (ch === ")" || ch === "]" || ch === "}") depth = Math.max(0, depth - 1);
  }
  return depth;
}

function collectTopLevelStatements(code: string): {
  hasDefOrClass: boolean;
  afterDefStatements: string[];
  allTopLevelStatements: string[];
} {
  const lines = (code || "").split("\n");
  let insideTripleQuote: '"""' | "'''" | null = null;
  let headerParenDepth = 0;
  let inHeaderContinuation = false;
  let seenDefOrClass = false;
  const allTopLevelStatements: string[] = [];
  const afterDefStatements: string[] = [];

  for (const rawLine of lines) {
    const trimmed = rawLine.trim();
    if (!trimmed) continue;

    if (insideTripleQuote) {
      if (trimmed.includes(insideTripleQuote)) {
        insideTripleQuote = null;
      }
      continue;
    }
    const doubleTripleMatches = trimmed.split('"""').length - 1;
    if (doubleTripleMatches % 2 === 1) {
      insideTripleQuote = '"""';
      continue;
    }
    const singleTripleMatches = trimmed.split("'''").length - 1;
    if (singleTripleMatches % 2 === 1) {
      insideTripleQuote = "'''";
      continue;
    }

    if (inHeaderContinuation) {
      headerParenDepth = updateParenDepth(rawLine, headerParenDepth);
      if (headerParenDepth === 0) {
        inHeaderContinuation = false;
      }
      continue;
    }

    if (/^\s/.test(rawLine) || trimmed.startsWith("#")) continue;

    if (
      trimmed.startsWith("def ") ||
      trimmed.startsWith("class ") ||
      trimmed.startsWith("import ") ||
      trimmed.startsWith("from ") ||
      trimmed.startsWith("@") ||
      trimmed === "pass"
    ) {
      if (trimmed.startsWith("def ") || trimmed.startsWith("class ")) {
        seenDefOrClass = true;
      }
      headerParenDepth = updateParenDepth(rawLine, 0);
      if (headerParenDepth > 0) {
        inHeaderContinuation = true;
      }
      continue;
    }

    allTopLevelStatements.push(trimmed);
    if (seenDefOrClass) {
      afterDefStatements.push(trimmed);
    }
  }

  return {
    hasDefOrClass: seenDefOrClass,
    afterDefStatements,
    allTopLevelStatements,
  };
}

function hasTopLevelExecution(userCode: string): boolean {
  return collectTopLevelStatements(userCode).allTopLevelStatements.length > 0;
}

function extractInvocationTarget(userCode: string): {
  kind: "method" | "function";
  className?: string;
  fnName: string;
  paramCount: number;
  paramListRaw: string;
} | null {
  const classMatch = userCode.match(
    /^class\s+([a-zA-Z_]\w*)[\s\S]*?^[ \t]+def\s+(?!__init__\b)([a-zA-Z_]\w*)\s*\(([^)]*)\)/m,
  );
  if (classMatch) {
    return {
      kind: "method",
      className: classMatch[1],
      fnName: classMatch[2],
      paramCount: countDeclaredParams(classMatch[3]),
      paramListRaw: classMatch[3],
    };
  }

  const fnMatch = userCode.match(/^def\s+([a-zA-Z_]\w*)\s*\(([^)]*)\)/m);
  if (fnMatch) {
    return {
      kind: "function",
      fnName: fnMatch[1],
      paramCount: countDeclaredParams(fnMatch[2]),
      paramListRaw: fnMatch[2],
    };
  }

  return null;
}

function extractTrailingCallsFromGuidedCode(
  guidedCode: string | undefined,
  expectedFnName: string,
): string | null {
  if (!guidedCode) return null;
  const normalized = guidedCode.replace(/\\n/g, "\n");
  const { hasDefOrClass, afterDefStatements } =
    collectTopLevelStatements(normalized);
  if (!hasDefOrClass || afterDefStatements.length === 0) return null;
  const joined = afterDefStatements.join("\n");
  return joined.includes(expectedFnName) ? joined : null;
}

function extractFirstHiddenCaseDriver(
  target: NonNullable<ReturnType<typeof extractInvocationTarget>>,
  hiddenTests: string | undefined,
): string | null {
  if (!hiddenTests) return null;
  const casesIdx = hiddenTests.search(/cases\s*=\s*\[/);
  if (casesIdx === -1) return null;

  const listOpen = hiddenTests.indexOf("[", casesIdx);
  if (listOpen === -1) return null;
  const casesBody = extractBalancedSlice(hiddenTests, listOpen, "[", "]");
  if (!casesBody) return null;

  const firstCase = splitTopLevelItems(casesBody)[0];
  if (!firstCase || !firstCase.startsWith("(") || !firstCase.endsWith(")")) {
    return null;
  }

  const innerCase = firstCase.slice(1, -1).trim();
  const caseParts = splitTopLevelItems(innerCase);
  if (caseParts.length === 0) return null;

  const rawArgSpec = caseParts[0];
  let formattedArgs = rawArgSpec;

  if (
    target.paramCount > 1 &&
    rawArgSpec.startsWith("(") &&
    rawArgSpec.endsWith(")")
  ) {
    formattedArgs = rawArgSpec.slice(1, -1).trim();
  } else if (target.paramCount === 0) {
    formattedArgs = "";
  }

  if (!isLiteralOnlyArgList(formattedArgs)) {
    return null;
  }

  if (target.kind === "method" && target.className) {
    // Detect constructor instantiation like `cache = LRUCache(2)` or `lb = LoadBalancer()`
    const ctorMatch = hiddenTests.match(
      new RegExp(`\\b${target.className}\\s*\\(`),
    );
    let ctorArgs = "";
    if (ctorMatch && ctorMatch.index !== undefined) {
      const parenIdx = hiddenTests.indexOf("(", ctorMatch.index);
      ctorArgs = (
        extractBalancedSlice(hiddenTests, parenIdx, "(", ")") || ""
      ).trim();
    }
    return `print(${target.className}(${ctorArgs}).${target.fnName}(${formattedArgs}))`;
  }
  if (target.kind === "function") {
    return `print(${target.fnName}(${formattedArgs}))`;
  }
  return null;
}

function isLiteralOnlyArgList(argsStr: string): boolean {
  const trimmed = argsStr.trim();
  if (!trimmed) return true;
  const items = splitTopLevelItems(trimmed);
  if (items.length === 0) return false;
  return items.every((item) => {
    const t = item.trim();
    return (
      t.startsWith("[") ||
      t.startsWith("{") ||
      t.startsWith("(") ||
      t.startsWith('"') ||
      t.startsWith("'") ||
      t === "True" ||
      t === "False" ||
      t === "None" ||
      /^-?\d+(?:\.\d+)?$/.test(t)
    );
  });
}

function extractFirstDirectCallFromHiddenTests(
  target: NonNullable<ReturnType<typeof extractInvocationTarget>>,
  hiddenTests: string | undefined,
): string | null {
  if (!hiddenTests) return null;

  if (target.kind === "function") {
    const callRegex = new RegExp(`\\b${target.fnName}\\s*\\(`, "g");
    let match: RegExpExecArray | null;
    while ((match = callRegex.exec(hiddenTests)) !== null) {
      const before = hiddenTests.slice(Math.max(0, match.index - 8), match.index);
      if (/\bdef\s+$/.test(before)) continue;
      const openIdx = hiddenTests.indexOf("(", match.index);
      const argsBody = extractBalancedSlice(hiddenTests, openIdx, "(", ")");
      if (argsBody === null) continue;
      if (isLiteralOnlyArgList(argsBody)) {
        return `print(${target.fnName}(${argsBody.trim()}))`;
      }
    }
  } else if (target.kind === "method" && target.className) {
    // Check stateful class sequence like `tb = TokenBucket(2)\nseq = [tb.allow_request(), ...]`
    const lines = hiddenTests.split("\n");
    const ctorAssignRegex = new RegExp(
      `^\\s*([a-zA-Z_]\\w*)\\s*=\\s*${target.className}\\(([^)]*)\\)\\s*$`,
    );
    for (let i = 0; i < lines.length; i++) {
      const m = lines[i].match(ctorAssignRegex);
      if (m && isLiteralOnlyArgList(m[2])) {
        const varName = m[1];
        const callLine = lines
          .slice(i + 1)
          .find(
            (l) =>
              l.includes(`${varName}.${target.fnName}(`) &&
              !l.includes("results.append"),
          );
        if (callLine) {
          const expr = callLine.trim().replace(/^[a-zA-Z_]\w*\s*=\s*/, "");
          return `${varName} = ${target.className}(${m[2]})\nprint(${expr})`;
        }
        return `${varName} = ${target.className}(${m[2]})\nprint(${varName}.${target.fnName}())`;
      }
    }
  }

  return null;
}

function extractExampleBasedDriver(
  target: NonNullable<ReturnType<typeof extractInvocationTarget>>,
  exampleInput: string | undefined,
): string | null {
  if (!exampleInput) return null;
  const trimmed = exampleInput.trim();
  if (!trimmed) return null;

  // Case 1: Example is already Python statements separated by ';' calling target/class
  if (
    trimmed.includes(`${target.fnName}(`) ||
    (target.className && trimmed.includes(`${target.className}(`))
  ) {
    const stmts = trimmed
      .split(";")
      .map((s) => s.trim())
      .filter(Boolean);
    if (stmts.length > 0) {
      const last = stmts[stmts.length - 1];
      const prefix = stmts.slice(0, -1);
      const wrappedLast = last.startsWith("print(") ? last : `print(${last})`;
      return [...prefix, wrappedLast].join("\n");
    }
  }

  // Case 2: Example is `var1 = val1, var2 = val2` or `quests = [10, 20, 5]`
  const assignParts = splitTopLevelItems(trimmed);
  if (assignParts.length > 0 && assignParts.every((p) => /^[a-zA-Z_]\w*\s*=/.test(p))) {
    const varNames = assignParts.map((p) => p.split("=")[0].trim());
    const callPrefix =
      target.kind === "method" && target.className
        ? `${target.className}().${target.fnName}`
        : target.fnName;
    if (varNames.length === target.paramCount) {
      return `${assignParts.join("\n")}\nprint(${callPrefix}(${varNames.join(", ")}))`;
    }
  }

  return null;
}

function buildFallbackDriverFromParams(
  target: NonNullable<ReturnType<typeof extractInvocationTarget>>,
): string {
  const rawParams = splitTopLevelItems(target.paramListRaw).filter(
    (p) => p && p !== "self" && p !== "cls",
  );
  const args = rawParams.map((param) => {
    const clean = param.split("=")[0].split(":")[0].trim().toLowerCase();
    if (
      clean.includes("map") ||
      clean.includes("dict") ||
      clean.includes("store") ||
      clean.includes("cache") ||
      clean.includes("flags") ||
      clean.includes("setting")
    ) {
      return '{"a": 1}';
    }
    if (
      clean.includes("word") ||
      clean.includes("name") ||
      clean.includes("guest") ||
      clean.includes("reaction")
    ) {
      return '["a", "b"]';
    }
    if (
      clean.includes("num") ||
      clean.includes("list") ||
      clean.includes("arr") ||
      clean.includes("price") ||
      clean.includes("quest") ||
      clean.includes("score") ||
      clean.includes("item") ||
      clean.includes("event") ||
      clean.includes("sample") ||
      clean.includes("server") ||
      clean.includes("player") ||
      clean.includes("vote") ||
      clean.includes("timestamp") ||
      clean.includes("edge") ||
      clean.includes("user") ||
      clean === "a" ||
      clean === "b"
    ) {
      return "[1, 2, 3]";
    }
    if (
      clean === "s" ||
      clean.includes("str") ||
      clean.includes("text") ||
      clean.includes("url") ||
      clean.includes("message") ||
      clean.includes("password") ||
      clean.includes("sentence") ||
      clean.includes("key") ||
      clean.includes("region") ||
      clean.includes("topic")
    ) {
      return '"abc"';
    }
    if (
      clean === "n" ||
      clean === "k" ||
      clean.includes("target") ||
      clean.includes("idx") ||
      clean.includes("count") ||
      clean.includes("limit") ||
      clean.includes("size") ||
      clean.includes("threshold") ||
      clean.includes("attempt") ||
      clean.includes("capacity")
    ) {
      return "3";
    }
    return "0";
  });

  if (target.kind === "method" && target.className) {
    return `print(${target.className}().${target.fnName}(${args.join(", ")}))`;
  }
  if (target.kind === "function") {
    return `print(${target.fnName}(${args.join(", ")}))`;
  }
  return "";
}

/**
 * Resolves an execution driver expression when student code defines a function
 * or class without a top-level call, so `sys.settrace` steps inside the logic.
 */
export function extractSampleTraceDriver(
  userCode: string,
  lesson?: Lesson | null,
  enrichment?: LessonEnrichment | null,
  customDriver?: string,
): TraceDriverResolution {
  const explicit = (customDriver || "").trim();
  if (explicit) {
    return { driverCode: explicit, autoGenerated: false };
  }

  if (hasTopLevelExecution(userCode)) {
    return { driverCode: "", autoGenerated: false };
  }

  const target = extractInvocationTarget(userCode);
  if (!target) {
    return { driverCode: "", autoGenerated: false };
  }

  const guidedTrailing = extractTrailingCallsFromGuidedCode(
    enrichment?.guidedCode,
    target.fnName,
  );
  if (guidedTrailing) {
    return { driverCode: guidedTrailing, autoGenerated: true };
  }

  const caseDriver = extractFirstHiddenCaseDriver(target, lesson?.hidden_tests);
  if (caseDriver) {
    return { driverCode: caseDriver, autoGenerated: true };
  }

  const directHiddenDriver = extractFirstDirectCallFromHiddenTests(
    target,
    lesson?.hidden_tests,
  );
  if (directHiddenDriver) {
    return { driverCode: directHiddenDriver, autoGenerated: true };
  }

  const exampleDriver = extractExampleBasedDriver(
    target,
    lesson?.examples?.[0]?.input,
  );
  if (exampleDriver) {
    return { driverCode: exampleDriver, autoGenerated: true };
  }

  const fallback = buildFallbackDriverFromParams(target);
  return {
    driverCode: fallback,
    autoGenerated: Boolean(fallback),
  };
}

/**
 * Wraps Python code inside a `sys.settrace` instrumentation runner that prints
 * a JSON payload describing line-by-line execution, locals, call stack, and stdout.
 */
export function buildPythonTraceRunnerScript(
  userCode: string,
  driverCode: string = "",
  maxSteps: number = 120,
): string {
  const safeMaxSteps = Math.max(10, Math.min(300, Math.floor(maxSteps)));
  const serializedUser = JSON.stringify(userCode || "");
  const serializedDriver = JSON.stringify(driverCode || "");

  return `import sys, io, json

__USER_CODE = ${serializedUser}
__DRIVER_CODE = ${serializedDriver}
__MAX_STEPS = ${safeMaxSteps}
__USER_LINES = __USER_CODE.splitlines()

__stdout_buf = io.StringIO()
__orig_stdout = sys.stdout
__frames = []
__frame_prev_locals = {}
__active_stack = []
__truncated = False
__runtime_error = None

class __TraceStepLimit(BaseException):
    pass

def __format_repr(val):
    try:
        r = repr(val)
    except Exception:
        r = "<unprintable>"
    if len(r) > 72:
        r = r[:69] + "..."
    return r

def __snapshot_locals(f_locals):
    snap = {}
    for k, v in list(f_locals.items()):
        if not isinstance(k, str) or k.startswith("__"):
            continue
        if isinstance(v, type) or callable(v):
            continue
        type_name = type(v).__name__
        if type_name == "module":
            continue
        snap[k] = {
            "value": __format_repr(v),
            "type": type_name,
        }
    return snap

def __trace_fn(frame, event, arg):
    global __truncated
    if __truncated:
        return None
    if frame.f_code.co_filename != "<student>":
        return __trace_fn

    func_name = frame.f_code.co_name
    if func_name == "<module>" and event in ("call", "return"):
        return __trace_fn if event == "call" else None

    if event not in ("call", "line", "return", "exception"):
        return __trace_fn

    fid = id(frame)
    if event == "call":
        __active_stack.append(func_name)
        __frame_prev_locals[fid] = {}

    lineno = int(frame.f_lineno or 1)
    code_line = __USER_LINES[lineno - 1].rstrip() if 1 <= lineno <= len(__USER_LINES) else ""
    curr_locals = __snapshot_locals(frame.f_locals)
    prev_locals = __frame_prev_locals.get(fid, {})
    changed = []
    for k, meta in curr_locals.items():
        if k not in prev_locals or prev_locals[k]["value"] != meta["value"] or prev_locals[k]["type"] != meta["type"]:
            meta["changed"] = True
            changed.append(k)
        else:
            meta["changed"] = False

    __frame_prev_locals[fid] = {
        k: {"value": v["value"], "type": v["type"]}
        for k, v in curr_locals.items()
    }

    ret_repr = __format_repr(arg) if event == "return" else None
    exc_text = None
    if event == "exception" and isinstance(arg, tuple) and len(arg) >= 2:
        try:
            exc_text = f"{arg[0].__name__}: {arg[1]}"
        except Exception:
            exc_text = "Runtime Exception"

    stack_snapshot = list(__active_stack) if __active_stack else ["<module>"]
    if func_name != "<module>" and (not stack_snapshot or stack_snapshot[-1] != func_name):
        stack_snapshot.append(func_name)

    __frames.append({
        "stepIndex": len(__frames),
        "line": lineno,
        "codeLine": code_line,
        "event": event,
        "funcName": func_name,
        "depth": max(0, len(__active_stack)),
        "callStack": stack_snapshot,
        "locals": curr_locals,
        "changedVars": changed,
        "returnValue": ret_repr,
        "exception": exc_text,
        "stdout": __stdout_buf.getvalue(),
    })

    if event == "return":
        if __active_stack and __active_stack[-1] == func_name:
            __active_stack.pop()
        __frame_prev_locals.pop(fid, None)

    if len(__frames) >= __MAX_STEPS:
        __truncated = True
        sys.settrace(None)
        raise __TraceStepLimit()

    return __trace_fn

__ns = {"__name__": "__main__"}
try:
    __compiled_user = compile(__USER_CODE, "<student>", "exec")
    __compiled_driver = None
    if __DRIVER_CODE.strip():
        try:
            __compiled_driver = compile(__DRIVER_CODE, "<driver>", "exec")
        except SyntaxError:
            __compiled_driver = None

    sys.stdout = __stdout_buf
    sys.settrace(__trace_fn)
    exec(__compiled_user, __ns)
    if __compiled_driver is not None and not __truncated:
        exec(__compiled_driver, __ns)
except __TraceStepLimit:
    __truncated = True
except SyntaxError as e:
    __runtime_error = f"SyntaxError (line {e.lineno or 1}): {e.msg}"
except Exception as e:
    __runtime_error = f"{type(e).__name__}: {e}"
finally:
    sys.settrace(None)
    sys.stdout = __orig_stdout

json.dumps({
    "ok": __runtime_error is None,
    "frames": __frames,
    "totalSteps": len(__frames),
    "truncated": __truncated,
    "driverUsed": __DRIVER_CODE,
    "finalStdout": __stdout_buf.getvalue().strip(),
    "error": __runtime_error,
})
`;
}

export function parsePythonTraceOutput(
  rawResult: unknown,
  fallbackDriver: string = "",
): PythonTraceResult {
  try {
    const parsed =
      typeof rawResult === "string" ? JSON.parse(rawResult) : rawResult;
    if (parsed && typeof parsed === "object" && Array.isArray((parsed as any).frames)) {
      const p = parsed as any;
      return {
        ok: Boolean(p.ok),
        frames: p.frames,
        totalSteps: Number(p.totalSteps ?? p.frames.length) || 0,
        truncated: Boolean(p.truncated),
        driverUsed: typeof p.driverUsed === "string" ? p.driverUsed : fallbackDriver,
        finalStdout: typeof p.finalStdout === "string" ? p.finalStdout : "",
        error: typeof p.error === "string" ? p.error : undefined,
      };
    }
  } catch {}

  return {
    ok: false,
    frames: [],
    totalSteps: 0,
    truncated: false,
    driverUsed: fallbackDriver,
    finalStdout: "",
    error: "Could not parse Python trace output.",
  };
}
