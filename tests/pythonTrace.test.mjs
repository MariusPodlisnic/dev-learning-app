import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import test from "node:test";
import { resolvePythonBinary } from "../scripts/contentAuditCore.mjs";
import { loadTsModule } from "./helpers/loadTs.mjs";

const {
  buildPythonTraceRunnerScript,
  extractSampleTraceDriver,
  parsePythonTraceOutput,
} = loadTsModule("src/utils/pythonTrace.ts");
const { getLessonEnrichment, mergeCurriculumLessons } = loadTsModule(
  "src/constants/curriculum.ts",
);

function runTraceInRealPython(userCode, driverCode = "", maxSteps = 120) {
  const pythonBin = resolvePythonBinary();
  assert.ok(pythonBin, "python3 binary should be available for trace tests");
  const script = buildPythonTraceRunnerScript(userCode, driverCode, maxSteps);
  const proc = spawnSync(
    pythonBin,
    [
      "-c",
      `import sys\nsrc = sys.stdin.read()\nns = {}\nexec(compile(src, "<harness>", "exec"), ns, ns)\nprint(eval("json.dumps({\\'ok\\': __runtime_error is None, \\'frames\\': __frames, \\'totalSteps\\': len(__frames), \\'truncated\\': __truncated, \\'driverUsed\\': __DRIVER_CODE, \\'finalStdout\\': __stdout_buf.getvalue().strip(), \\'error\\': __runtime_error})", ns))`,
    ],
    {
      input: script,
      encoding: "utf8",
      timeout: 5000,
    },
  );
  assert.equal(
    proc.status,
    0,
    `Python harness failed: ${proc.stderr || proc.stdout}`,
  );
  return parsePythonTraceOutput(proc.stdout.trim(), driverCode);
}

test("sys.settrace captures line steps, variable mutations, and incremental stdout", () => {
  const code = `total = 0
for n in [2, 5]:
    total += n
print("SUM:", total)`;

  const res = runTraceInRealPython(code);
  assert.equal(res.ok, true);
  assert.equal(res.truncated, false);
  assert.equal(res.finalStdout, "SUM: 7");
  assert.ok(res.frames.length >= 4);

  const mutatedTotalFrames = res.frames.filter((f) =>
    f.changedVars.includes("total"),
  );
  assert.ok(
    mutatedTotalFrames.length >= 2,
    "expected multiple mutations of `total`",
  );
  assert.equal(
    res.frames.some((f) => f.locals.total && f.locals.total.value === "7"),
    true,
  );
});

test("extractSampleTraceDriver synthesizes driver for function-only lesson and traces call/return", () => {
  const userCode = `class Solution:
    def twoSum(self, nums, target):
        seen = {}
        for i, num in enumerate(nums):
            needed = target - num
            if needed in seen:
                return [seen[needed], i]
            seen[num] = i
        return []`;

  const lesson = {
    hidden_tests: `import json
def __run_tests__():
    sol = Solution()
    cases = [(([2, 7, 11, 15], 9), [0, 1])]
`,
  };

  const { driverCode, autoGenerated } = extractSampleTraceDriver(
    userCode,
    lesson,
    null,
  );
  assert.equal(autoGenerated, true);
  assert.equal(driverCode, "print(Solution().twoSum([2, 7, 11, 15], 9))");

  const res = runTraceInRealPython(userCode, driverCode);
  assert.equal(res.ok, true);
  assert.equal(res.finalStdout, "[0, 1]");
  assert.ok(
    res.frames.some(
      (f) => f.event === "call" && f.funcName === "twoSum" && f.depth >= 1,
    ),
  );
  assert.ok(
    res.frames.some(
      (f) =>
        f.event === "return" &&
        f.funcName === "twoSum" &&
        f.returnValue === "[0, 1]",
    ),
  );
});

test("sys.settrace caps runaway loops cleanly at maxSteps", () => {
  const infiniteLoop = `i = 0
while True:
    i += 1`;

  const res = runTraceInRealPython(infiniteLoop, "", 25);
  assert.equal(res.truncated, true);
  assert.equal(res.totalSteps, 25);
  assert.equal(res.frames.length, 25);
});

test("sys.settrace reports syntax errors cleanly with line number", () => {
  const badCode = `x = 1\nif x == 1\n    print(x)`;
  const res = runTraceInRealPython(badCode);
  assert.equal(res.ok, false);
  assert.ok(res.error && res.error.includes("SyntaxError"));
  assert.ok(res.error.includes("line 2"));
});

test("sum_doubled_xp (exp-py-02) extracts direct hidden test call and traces cleanly", () => {
  const lessons = mergeCurriculumLessons([]);
  const lesson2 = lessons.find((l) => l.id === "exp-py-02");
  assert.ok(lesson2);
  const enrichment2 = getLessonEnrichment(lesson2);
  const userCode = `def sum_doubled_xp(quests):
    total = 0
    for xp in quests:
        total += xp * 2
    return total`;

  const { driverCode, autoGenerated } = extractSampleTraceDriver(
    userCode,
    lesson2,
    enrichment2,
  );
  assert.equal(autoGenerated, true);
  assert.equal(driverCode, "print(sum_doubled_xp([10, 20, 5]))");

  const res = runTraceInRealPython(userCode, driverCode);
  assert.equal(res.ok, true);
  assert.equal(res.finalStdout, "70");
  assert.ok(res.frames.some((f) => f.funcName === "sum_doubled_xp"));
  assert.ok(res.frames.some((f) => f.returnValue === "70"));
});

test("all 100 core lesson solutions trace cleanly under sys.settrace without driver TypeErrors", () => {
  const lessons = mergeCurriculumLessons([]);
  const pythonBin = resolvePythonBinary();
  assert.ok(pythonBin);

  const failures = [];
  for (const lesson of lessons) {
    const enrichment = getLessonEnrichment(lesson);
    if (!enrichment?.solutionCode) continue;
    const { driverCode } = extractSampleTraceDriver(
      enrichment.solutionCode,
      lesson,
      enrichment,
    );
    const res = runTraceInRealPython(enrichment.solutionCode, driverCode, 120);
    if (!res.ok || res.frames.length < 2) {
      failures.push({
        id: lesson.id,
        title: lesson.title,
        driverCode,
        error: res.error,
        frames: res.frames.length,
      });
    }
  }

  assert.deepEqual(failures, [], `Trace failures: ${JSON.stringify(failures)}`);
});
